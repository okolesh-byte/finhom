class Command(BaseCommand):
    help = 'Создаёт шесть дополнительных статей и комментарии к ним'

    def handle(self, *args, **options):
        try:
            admin = User.objects.get(email='admin@finhom.local')
        except User.DoesNotExist as error:
            raise CommandError('Сначала выполните команду seed_demo.') from error

        categories = {item.slug: item for item in ArticleCategory.objects.all()}
        published_at = timezone.now()

        for index, item in enumerate(ARTICLES, start=1):
            category = categories.get(item['category'])
            if not category:
                raise CommandError(f'Не найдена категория {item["category"]}.')

            article, _ = Article.objects.update_or_create(
                title=item['title'],
                defaults={
                    'category': category,
                    'author': admin,
                    'summary': item['summary'],
                    'body': item['body'],
                    'published_at': published_at - timedelta(days=index * 3),
                    'is_published': True,
                },
            )

            for email, text in item['comments']:
                try:
                    author = User.objects.get(email=email)
                except User.DoesNotExist as error:
                    raise CommandError(f'Не найден тестовый аккаунт {email}.') from error
                Comment.objects.get_or_create(
                    article=article,
                    author=author,
                    text=text,
                    defaults={'status': Comment.PUBLISHED, 'moderator_note': ''},
                )

        self.stdout.write(self.style.SUCCESS('Добавлено 6 статей и 12 опубликованных комментариев.'))
